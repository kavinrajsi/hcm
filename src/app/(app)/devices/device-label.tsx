import { cn } from "@/lib/utils";

// Small L-shaped ticks in each corner of the label. Where four labels meet,
// the ticks line up into a cross, showing exactly where to cut.
const CUT_MARKS = [
  "top-0 left-0 border-t border-l",
  "top-0 right-0 border-t border-r",
  "bottom-0 left-0 border-b border-l",
  "bottom-0 right-0 border-b border-r",
];

/**
 * The sticker: just the QR code, centred, with cutting marks in the corners.
 * Sized in millimetres so it prints true on an A4 sheet, 4 labels across
 * (52.5 × 37 mm).
 */
export function DeviceLabel({ svg, className }: { svg: string; className?: string }) {
  return (
    <div className={cn("relative flex h-[37mm] w-[52.5mm] items-center justify-center overflow-hidden bg-white p-[3mm] text-black", className)}>
      {CUT_MARKS.map((position) => (
        <span
          key={position}
          aria-hidden
          className={cn("absolute size-[2.5mm] border-black", position)}
          style={{ borderWidth: "0.2mm" }}
        />
      ))}
      <div
        className="size-[31mm] [&>svg]:size-full"
        // Generated by the qrcode library from our own URL, not user input.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
    </div>
  );
}
